// Generates every app icon from one mark: a crimson film reel with its tape running out flat,
// like a line in a log. Writes the SVG favicon, the Android adaptive-icon vectors, and PNGs
// (rendered with rsvg-convert, from librsvg).
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const BG = '#0C0A0A', GLOW = '#3A0C14', HI = '#D42037', LO = '#8C0E1E';

// Mark geometry in a 512 design grid, centred on 0,0. Outlines run clockwise and holes
// anticlockwise, so it fills correctly with the default nonzero rule.
const n = (v) => +v.toFixed(2);
const circle = (cx, cy, r, cw = true) =>
  `M${n(cx + r)},${n(cy)} A${r},${r} 0 1 ${+cw} ${n(cx - r)},${n(cy)} A${r},${r} 0 1 ${+cw} ${n(cx + r)},${n(cy)} Z`;
const R = 128, CX = -8;
const holes = [0, 1, 2, 3, 4].map((k) => {
  const a = ((-90 + k * 72) * Math.PI) / 180;
  return circle(CX + 70 * Math.cos(a), 70 * Math.sin(a), 28, false);
});
const tape = `M${CX},100 H122 A14,14 0 0 1 122,128 H${CX} Z`;
const MARK = [circle(CX, 0, R), tape, ...holes, circle(CX, 0, 14, false)].join(' ');

const svg = ({ tile = 'rounded', scale = 1 }) => {
  const shape =
    tile === 'rounded' ? '<rect width="512" height="512" rx="112" fill="url(#bg)"/>'
    : tile === 'round' ? '<circle cx="256" cy="256" r="256" fill="url(#bg)"/>'
    : '<rect width="512" height="512" fill="url(#bg)"/>';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
<defs>
<radialGradient id="bg" cx="50%" cy="42%" r="62%"><stop offset="0" stop-color="${GLOW}"/><stop offset="1" stop-color="${BG}"/></radialGradient>
<linearGradient id="mk" x1="0" y1="-128" x2="0" y2="128" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${HI}"/><stop offset="1" stop-color="${LO}"/></linearGradient>
</defs>
${shape}
<path transform="translate(256 256) scale(${scale})" fill="url(#mk)" d="${MARK}"/>
</svg>
`;
};

// Android adaptive icon: 108dp canvas, launchers keep the central 66dp circle.
const S = 0.17;
const androidFg = (fill) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.mjs. Reelog mark: film reel with its tape running out flat. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="54" android:translateY="54" android:scaleX="${S}" android:scaleY="${S}">
        <path android:pathData="${MARK}"${fill}
    </group>
</vector>
`;
const gradientFill = `>
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="0" android:startY="-128" android:endX="0" android:endY="128"
                    android:startColor="${HI}" android:endColor="${LO}" />
            </aapt:attr>
        </path>`;
const androidBg = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.mjs. Near-black with a faint crimson glow behind the mark. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0 H108 V108 H0 Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="48" android:gradientRadius="60"
                android:startColor="${GLOW}" android:endColor="${BG}" />
        </aapt:attr>
    </path>
</vector>
`;

const RES = 'android/app/src/main/res';
writeFileSync(`${RES}/drawable/ic_reelog_foreground.xml`, androidFg(gradientFill));
writeFileSync(`${RES}/drawable/ic_reelog_monochrome.xml`, androidFg(` android:fillColor="#FFFFFF" />`));
writeFileSync(`${RES}/drawable/ic_reelog_background.xml`, androidBg);
writeFileSync('public/icon.svg', svg({}));

const tmp = mkdtempSync(join(tmpdir(), 'reelog-icons-'));
const png = (out, px, opts) => {
  const src = join(tmp, 'icon.svg');
  writeFileSync(src, svg(opts));
  execFileSync('rsvg-convert', ['-w', String(px), '-h', String(px), '-o', out, src]);
};
// Legacy launcher icons for Android < 8 (newer versions use the adaptive vectors above).
for (const [dir, px] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
  png(`${RES}/mipmap-${dir}/ic_launcher.png`, px, { tile: 'rounded', scale: 0.86 });
  png(`${RES}/mipmap-${dir}/ic_launcher_round.png`, px, { tile: 'round', scale: 0.8 });
}
png('public/icon-192.png', 192, { tile: 'rounded' });
png('public/icon-512.png', 512, { tile: 'rounded' });
png('public/icon-maskable-512.png', 512, { tile: 'square', scale: 0.72 });
console.log('icons written');
